SELECT BOOK.AUTHOR_ID, AUTHOR_NAME, CATEGORY, SUM(SALES * PRICE) AS TOTAL_SALES
FROM BOOK
JOIN AUTHOR ON BOOK.AUTHOR_ID = AUTHOR.AUTHOR_ID
JOIN BOOK_SALES ON BOOK.BOOK_ID = BOOK_SALES.BOOK_ID
WHERE DATE_FORMAT(SALES_DATE, '%Y') = '2022'
AND DATE_FORMAT(SALES_DATE, '%m') = '01'
GROUP BY CATEGORY, BOOK.AUTHOR_ID
ORDER BY BOOK.AUTHOR_ID, CATEGORY DESC